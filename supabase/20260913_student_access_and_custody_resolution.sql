-- يسجل الطالب جهازه الحالي بعد الدخول؛ الأدوار الأخرى لا تنشئ صفوفاً هنا.
CREATE OR REPLACE FUNCTION public.register_current_student_device(p_device TEXT)
RETURNS VOID LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_center UUID; v_student TEXT;
BEGIN
  IF auth.uid() IS NULL OR p_device IS NULL OR length(trim(p_device)) < 8 OR length(trim(p_device)) > 128 THEN RETURN; END IF;
  SELECT center_id, student_id INTO v_center, v_student
  FROM public.profiles WHERE id = auth.uid() AND role = 'student';
  IF v_center IS NULL OR v_student IS NULL THEN RETURN; END IF;
  IF NOT EXISTS (SELECT 1 FROM public.students WHERE id = v_student AND center_id = v_center) THEN RETURN; END IF;

  INSERT INTO public.student_device_sessions(center_id, student_id, device_id, last_seen)
  VALUES(v_center, v_student, trim(p_device), now())
  ON CONFLICT(center_id, student_id, device_id) DO UPDATE SET last_seen = now();
  UPDATE public.user_active_sessions SET device_id = trim(p_device)
  WHERE user_id = auth.uid();
END;
$$;
GRANT EXECUTE ON FUNCTION public.register_current_student_device(TEXT) TO authenticated;

-- يفحصه العميل دورياً مع الجلسة. لا يوجد سجل للجهاز = متاح (توافق مع الأجهزة القديمة).
CREATE OR REPLACE FUNCTION public.check_current_student_device(p_device TEXT)
RETURNS BOOLEAN LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
DECLARE v_center UUID; v_student TEXT; v_role TEXT;
BEGIN
  IF auth.uid() IS NULL THEN RETURN false; END IF;
  SELECT role, center_id, student_id INTO v_role, v_center, v_student FROM public.profiles WHERE id = auth.uid();
  IF v_role IS DISTINCT FROM 'student' THEN RETURN true; END IF;
  IF v_center IS NULL OR v_student IS NULL OR p_device IS NULL OR trim(p_device) = '' THEN RETURN true; END IF;
  RETURN NOT EXISTS (
    SELECT 1 FROM public.student_device_sessions
    WHERE center_id = v_center AND student_id = v_student AND device_id = trim(p_device) AND blocked
  );
END;
$$;
GRANT EXECUTE ON FUNCTION public.check_current_student_device(TEXT) TO authenticated;

-- لا تعرض الأجهزة إلا لصاحب السنتر الذي يملك الطالب ذاته.
CREATE OR REPLACE FUNCTION public.list_student_devices(p_student TEXT)
RETURNS JSONB LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
DECLARE v_center UUID := public.my_center_id();
BEGIN
  IF v_center IS NULL OR NOT public.admin_owns_center(v_center)
     OR NOT EXISTS (SELECT 1 FROM public.students WHERE id = p_student AND center_id = v_center) THEN
    RAISE EXCEPTION 'not_allowed';
  END IF;
  RETURN COALESCE((SELECT jsonb_agg(jsonb_build_object(
    'id', id, 'center_id', center_id, 'student_id', student_id, 'device_id', device_id,
    'blocked', blocked, 'note', note, 'first_seen', first_seen, 'last_seen', last_seen, 'blocked_at', blocked_at
  ) ORDER BY last_seen DESC) FROM public.student_device_sessions
  WHERE center_id = v_center AND student_id = p_student), '[]'::JSONB);
END;
$$;
GRANT EXECUTE ON FUNCTION public.list_student_devices(TEXT) TO authenticated;

-- حجب جهاز واحد أو إلغاء حجبه. عند الحجب تنتهي جلسة هذا الجهاز فقط فور الفحص التالي.
CREATE OR REPLACE FUNCTION public.set_student_device_blocked(
  p_student TEXT, p_device TEXT, p_blocked BOOLEAN, p_note TEXT DEFAULT ''
)
RETURNS VOID LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_center UUID := public.my_center_id(); v_updated INT;
BEGIN
  IF v_center IS NULL OR NOT public.admin_owns_center(v_center)
     OR NOT EXISTS (SELECT 1 FROM public.students WHERE id = p_student AND center_id = v_center) THEN
    RAISE EXCEPTION 'not_allowed';
  END IF;
  IF p_device IS NULL OR length(trim(p_device)) < 8 THEN RAISE EXCEPTION 'invalid_device'; END IF;
  UPDATE public.student_device_sessions
  SET blocked = COALESCE(p_blocked, false), note = COALESCE(trim(p_note), ''),
      blocked_at = CASE WHEN p_blocked THEN now() ELSE NULL END
  WHERE center_id = v_center AND student_id = p_student AND device_id = trim(p_device);
  GET DIAGNOSTICS v_updated = ROW_COUNT;
  IF v_updated = 0 THEN RAISE EXCEPTION 'student_device_not_found'; END IF;
  IF p_blocked THEN
    DELETE FROM public.user_active_sessions uas
    USING public.profiles p
    WHERE p.id = uas.user_id AND p.student_id = p_student AND p.center_id = v_center
      AND uas.device_id = trim(p_device);
  END IF;
END;
$$;
GRANT EXECUTE ON FUNCTION public.set_student_device_blocked(TEXT, TEXT, BOOLEAN, TEXT) TO authenticated;

