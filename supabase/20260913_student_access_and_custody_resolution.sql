CREATE TABLE IF NOT EXISTS public.user_active_sessions (
  user_id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  session_key TEXT NOT NULL,
  started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  last_seen TIMESTAMPTZ NOT NULL DEFAULT now()
);
ALTER TABLE public.user_active_sessions ENABLE ROW LEVEL SECURITY;

CREATE OR REPLACE FUNCTION public.claim_session(p_key TEXT)
RETURNS VOID LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF auth.uid() IS NULL THEN RAISE EXCEPTION 'not_authenticated'; END IF;
  IF p_key IS NULL OR length(trim(p_key)) < 8 OR length(trim(p_key)) > 128 THEN RAISE EXCEPTION 'invalid_session_key'; END IF;
  INSERT INTO public.user_active_sessions(user_id, session_key, started_at, last_seen)
  VALUES(auth.uid(), trim(p_key), now(), now())
  ON CONFLICT (user_id) DO UPDATE SET session_key = EXCLUDED.session_key, started_at = now(), last_seen = now();
END;
$$;
GRANT EXECUTE ON FUNCTION public.claim_session(TEXT) TO authenticated;

CREATE OR REPLACE FUNCTION public.check_session(p_key TEXT)
RETURNS BOOLEAN LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF auth.uid() IS NULL THEN RETURN false; END IF;
  IF NOT EXISTS (SELECT 1 FROM public.user_active_sessions WHERE user_id = auth.uid() AND session_key = p_key) THEN RETURN false; END IF;
  UPDATE public.user_active_sessions SET last_seen = now() WHERE user_id = auth.uid() AND session_key = p_key;
  RETURN true;
END;
$$;
GRANT EXECUTE ON FUNCTION public.check_session(TEXT) TO authenticated;

